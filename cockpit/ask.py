"""The cockpit: one question in, a short answer out, with the records behind it.

Design choice (see DECISIONS.md D-03): answers are assembled deterministically from SQL, not
generated by an LLM. Every number therefore traces to a row, and the engine can say "I don't
have that" instead of guessing. An LLM is used only for the agent interviews (agents.py).
"""
import re
from collections import defaultdict

from .resolve import find_person


def inr(x):
    x = float(x)
    if abs(x) >= 1e7:
        return f"Rs {x / 1e7:.2f} Cr"
    if abs(x) >= 1e5:
        return f"Rs {x / 1e5:.2f} L"
    return f"Rs {x:,.0f}"


def refs(rows_or_refs):
    """Collapse ['f.xlsx!R5','f.xlsx!R8'] -> ['f.xlsx rows 5, 8']."""
    by = defaultdict(list)
    for r in rows_or_refs:
        if "!R" in r:
            f, n = r.rsplit("!R", 1)
            by[f].append(n)
        else:
            by[r].append(None)
    out = []
    for f, ns in by.items():
        ns = [n for n in ns if n]
        out.append(f"{f} rows {', '.join(ns)}" if ns else f)
    return out


def reply(answer, cites=(), confidence="High", caveats=()):
    return {"answer": answer, "cites": refs(cites), "confidence": confidence, "caveats": list(caveats)[:2]}


# --------------------------------------------------------------------------- handlers
def h_privacy(con, q, ql):
    if re.search(r"salary|salaries|\bpay\b|\bpaid\b|ctc|earn|compensation|gross|net pay|how much does", ql):
        emp = find_person(con, q)
        if emp:
            p = con.execute("SELECT full_name FROM person WHERE emp_id=?", (emp,)).fetchone()
            return reply(f"I can't share individual pay, only totals (that's the CFO's rule). I can give total payroll "
                         f"by month instead.", ["T2_CFO_Call.docx"], "High")
    return None


def h_worry(con, q, ql):
    if not re.search(r"worry|worried|risk|concern|problem|stuck|wrong|issue|attention|red flag|trouble", ql):
        return None
    rows = con.execute("SELECT * FROM finding ORDER BY severity DESC, id").fetchall()
    top = rows[:5]
    txt = " ".join(f"({i}) {r['title']}." for i, r in enumerate(top, 1))
    return reply(f"Top things to worry about: {txt} The worry view has all {len(rows)}.",
                 [e for r in top for e in r["evidence"].split("; ")[:1]], "Medium",
                 ["The ranking is my judgement."])


def h_payroll_error(con, q, ql):
    if not re.search(r"overpa|payslip|prorat|payroll (error|mistake|issue|problem)", ql):
        return None
    rows = con.execute("SELECT * FROM finding WHERE kind='payroll' ORDER BY id").fetchall()
    if not rows:
        return reply("I found no payroll proration errors in the register.", ["Payroll_Register_Jan-Mar_2026.xlsx"], "Medium")
    r = rows[0]
    return reply(f"{r['title']}. {r['detail']}", r["evidence"].split("; "), "High",
                 ["The amount is an estimate from the payroll register."])


def h_payroll_total(con, q, ql):
    if not re.search(r"payroll|salary cost|salaries|wage|people cost|total pay|staff cost", ql):
        return None
    reg = con.execute("SELECT month, SUM(gross) g, COUNT(*) n, MIN(src_ref) r FROM payroll "
                      "GROUP BY month ORDER BY MIN(rowid)").fetchall()
    gl = con.execute("SELECT txn_date, amount, src_ref FROM gl_entry WHERE cost_centre='PAYROLL' ORDER BY txn_date").fetchall()
    a = ", ".join(f"{r['month']} {inr(r['g'])} ({r['n']} staff)" for r in reg)
    b = f"{inr(gl[0]['amount'])} every month Apr-Sep" if len({x['amount'] for x in gl}) == 1 else \
        ", ".join(f"{x['txn_date'][:7]} {inr(x['amount'])}" for x in gl)
    return reply(f"Total gross payroll (totals only): register Jan-Mar: {a}. Books (GL) show {b}.",
                 [r["r"] for r in reg] + [x["src_ref"] for x in gl], "High",
                 ["The books show the same amount six months running, which looks copied forward.",
                  "Jan-Mar and Apr-Sep come from different systems."])


def h_headcount(con, q, ql):
    if not re.search(r"headcount|head count|how many (people|employees|staff)|team size|number of (people|employees)|company size", ql):
        return None
    by = con.execute("SELECT status, COUNT(*) n, GROUP_CONCAT(src_ref) r FROM person GROUP BY status").fetchall()
    total = sum(r["n"] for r in by)
    dept = con.execute("SELECT dept, COUNT(*) n FROM person GROUP BY dept ORDER BY n DESC").fetchall()
    bd = con.execute("SELECT * FROM board_update ORDER BY sent_on DESC LIMIT 1").fetchone()
    return reply(f"Veloxa has {total} people in Keka ({', '.join(f'{r['n']} {r['status']}' for r in by)}). "
                 f"By department: {', '.join(f'{r['dept']} {r['n']}' for r in dept)}. "
                 f"The latest board update also says {bd['team']}.",
                 ["Employee_Master.xlsx"] + [bd["src_ref"]], "High",
                 ["Nothing in the data supports the ~180 mentioned on the call. Contractors aren't in Keka."])


def h_arr(con, q, ql):
    if not re.search(r"\barr\b|recurring revenue|revenue|customers", ql):
        return None
    rows = con.execute("SELECT * FROM board_update ORDER BY sent_on").fetchall()
    txt = "; ".join(f"{r['period']}: ARR Rs {r['arr_cr']} Cr, {r['customers']} customers" for r in rows)
    return reply(f"ARR per the board updates: {txt}. Growth {rows[0]['arr_cr']} -> {rows[-1]['arr_cr']} Cr "
                 f"({(rows[-1]['arr_cr'] / rows[0]['arr_cr'] - 1) * 100:.0f}% in one quarter).",
                 [r["src_ref"] for r in rows], "Medium",
                 ["The kickoff call said '42-45 crore'; the board says 6.1 Cr, so I went with the board.",
                  "Board figures are self-reported; there's no billing data to check them."])


def h_burn(con, q, ql):
    if not re.search(r"burn|runway|cash", ql):
        return None
    rows = con.execute("SELECT * FROM board_update ORDER BY sent_on").fetchall()
    txt = "; ".join(f"{r['period']}: burn Rs {r['burn_lakh']:.0f} L/month, runway {r['runway_months']} months" for r in rows)
    return reply(f"Burn and runway per the board: {txt}.", [r["src_ref"] for r in rows], "Medium",
                 ["The '2.2 lakh' burn on the calls can't be right: payroll alone is Rs 31.75 L a month.",
                  "The ledger export is partial, so I can't recompute burn myself."])


def h_marketing(con, q, ql):
    if not re.search(r"marketing|summit|event|\bads?\b|google|campaign", ql):
        return None
    ev = con.execute("SELECT vendor_raw, amount, txn_date, narration, src_ref FROM gl_entry WHERE cost_centre='MKT-EVT' ORDER BY txn_date").fetchall()
    ads = con.execute("SELECT SUM(amount) s, COUNT(*) n FROM gl_entry WHERE cost_centre='MKT-PS'").fetchone()
    evt = sum(r["amount"] for r in ev)
    bd = con.execute("SELECT narrative FROM board_update ORDER BY sent_on DESC LIMIT 1").fetchone()
    reg = re.search(r"drew (\d+) registrations", bd["narrative"])
    lines = "; ".join(f"{r['txn_date']} {r['vendor_raw']} {inr(r['amount'])} ({r['narration']})" for r in ev)
    per = f" That is about {inr(evt / int(reg.group(1)))} per registration." if reg else ""
    return reply(f"Marketing spend in the books: Summit {inr(evt)} across two similarly named vendors ({lines}); "
                 f"Google Ads {inr(ads['s'])} over {ads['n']} months.{per}",
                 [r["src_ref"] for r in ev] + ["GL_Export_Apr-Sep_2026.xlsx"], "Medium",
                 ["'Sapphire Events' and 'Saphire Event Mgmt' may be the same vendor; I kept them separate.",
                  "The ledger is partial, and Nikhil's own figures aren't loaded, so I can't say whose total is right."])


def h_cloud(con, q, ql):
    if not re.search(r"aws|cloud|hosting|infra|server", ql):
        return None
    rows = con.execute("SELECT txn_date, amount, src_ref FROM gl_entry WHERE vendor_id='AWS' ORDER BY txn_date").fetchall()
    txt = ", ".join(f"{r['txn_date'][5:7]}/{r['txn_date'][:4]} {inr(r['amount'])}" for r in rows)
    g = (rows[-1]["amount"] / rows[0]["amount"] - 1) * 100
    return reply(f"AWS bills (booked monthly in arrears): {txt}. Up {g:.0f}% from first to last.",
                 [r["src_ref"] for r in rows], "High",
                 ["The cause isn't in the data; there's no usage breakdown."])


def h_hiring(con, q, ql):
    if not re.search(r"hiring|backend|recruit|open role|freeze|headcount plan|vacanc", ql):
        return None
    f = con.execute("SELECT * FROM finding WHERE id='F-HIRE'").fetchone()
    return reply(f"{f['title']}. {f['detail']}", f["evidence"].split("; "), "Medium",
                 ["The hiring tracker isn't loaded yet, so open roles are unconfirmed."])


def h_attrition(con, q, ql):
    if not re.search(r"attrition|resign|leaving|notice|exit|quit|churn", ql):
        return None
    rows = con.execute("SELECT * FROM person WHERE status != 'Active'").fetchall()
    txt = "; ".join(f"{r['full_name']} ({r['title']}) leaving {r['exit_date']}" for r in rows)
    return reply(f"Known departures: {txt}. That is {len(rows)} of {con.execute('SELECT COUNT(*) FROM person').fetchone()[0]} "
                 f"people on the Keka export.",
                 [r["src_ref"] for r in rows], "Low",
                 ["I can't give an attrition rate: the HR export lists current staff only, so past leavers aren't visible."])


def h_atlas(con, q, ql):
    if not re.search(r"atlas|routing|launch|\bga\b|v3|festive|release date|ship", ql):
        return None
    f = con.execute("SELECT * FROM finding WHERE id='F-ATLAS'").fetchone()
    return reply(f"{f['title']}. {f['detail']}", ["Board_Update_Apr-Jun_2026.pdf", "Board_Update_Jul-Sep_2026.pdf"], "Medium",
                 ["Jira, git and the launch kit aren't loaded yet; this is only what the board and the call said."])


def h_vendor(con, q, ql):
    if not re.search(r"vendor|duplicate|saphire|sapphire|supplier", ql):
        return None
    rows = con.execute("SELECT * FROM finding WHERE kind='vendor' ORDER BY severity DESC").fetchall()
    return reply(" ".join(f"{r['title']}. {r['detail']}" for r in rows),
                 [e for r in rows for e in r["evidence"].split("; ")], "Medium")


def h_conflicts(con, q, ql):
    if not re.search(r"conflict|contradict|disagree|which (number|source)|trust|misheard|inconsisten", ql):
        return None
    rows = con.execute("SELECT * FROM claim WHERE confidence IN ('H','M') AND resolved NOT LIKE 'Design%' ORDER BY id").fetchall()
    txt = " ".join(f"[{r['id']}] Heard: {r['as_heard']} -> {r['resolved']}." for r in rows[:6])
    return reply(f"Where what people said disagrees with the records: {txt}",
                 [f"claim {r['id']} ({r['evidence']})" for r in rows[:6]], "Medium",
                 ["Full list with reasoning is in TRANSCRIPT_NOTES.md."])


def h_team(con, q, ql):
    m = re.search(r"\b(engineering|finance|marketing|people|hr|sales|support|leadership)\b", ql)
    if not m:
        return None
    key = {"hr": "People & Ops", "people": "People & Ops"}.get(m.group(1), m.group(1).title())
    rows = con.execute("SELECT * FROM person WHERE dept=? ORDER BY join_date", (key,)).fetchall()
    if not rows:
        return None
    txt = "; ".join(f"{r['full_name']} - {r['title']}" + (f" ({r['status'].lower()})" if r["status"] != "Active" else "") for r in rows)
    return reply(f"{key} has {len(rows)} people: {txt}.", [r["src_ref"] for r in rows], "High",
                 ["I only have roles so far; what each person works on needs Jira, git and email data."])


def h_person(con, q, ql):
    emp = find_person(con, q)
    if not emp:
        return None
    p = con.execute("SELECT * FROM person WHERE emp_id=?", (emp,)).fetchone()
    mgr = con.execute("SELECT full_name FROM person WHERE emp_id=?", (p["manager_id"],)).fetchone()
    mails = con.execute("SELECT * FROM message WHERE sender LIKE ? OR recipient LIKE ?",
                        (f"%{p['email']}%", f"%{p['email']}%")).fetchall()
    fnds = con.execute("SELECT title FROM finding WHERE id LIKE ? OR evidence LIKE ?",
                       (f"%{emp}%", f"%{p['full_name']}%")).fetchall()
    txt = (f"{p['full_name']} is {p['title']} in {p['dept']}, based in {p['location']}, "
           f"joined {p['join_date']}" + (f", reports to {mgr['full_name']}" if mgr else "") +
           f", status {p['status']}" + (f" (last day {p['exit_date']})" if p["exit_date"] else "") + ".")
    if mails:
        txt += f" Appears in {len(mails)} email(s) in the data room."
    if fnds:
        txt += " Related issue: " + "; ".join(f["title"] for f in fnds) + "."
    return reply(txt, [p["src_ref"]] + [m["src_ref"] for m in mails], "High",
                 ["To talk to them directly, use the People view."])


HANDLERS = [h_privacy, h_worry, h_payroll_error, h_payroll_total, h_headcount, h_arr, h_burn, h_marketing,
            h_cloud, h_hiring, h_attrition, h_atlas, h_vendor, h_conflicts, h_team, h_person]


def fallback(con, q):
    """Last resort: keyword search over free text. If nothing matches we say so."""
    words = [w for w in re.findall(r"[a-z]{4,}", q.lower()) if w not in
             {"what", "when", "where", "which", "about", "does", "have", "with", "this", "that", "from", "tell", "give"}]
    hits = []
    for w in words:
        for r in con.execute("SELECT doc_id, title, src_ref, body FROM document WHERE lower(body) LIKE ?", (f"%{w}%",)):
            hits.append((r["doc_id"], r["src_ref"]))
        for r in con.execute("SELECT subject, src_ref FROM message WHERE lower(body||subject) LIKE ?", (f"%{w}%",)):
            hits.append((r["subject"], r["src_ref"]))
    if not hits:
        return reply("I don't have anything on that in the data.", [], "None",
                     ["Try headcount, ARR, burn, payroll totals, marketing spend, AWS, hiring, Atlas, a person, or 'what should I worry about'."])
    uniq = list(dict.fromkeys(hits))[:4]
    return reply("I can't answer that directly, but these records mention it: " + "; ".join(f"{a} ({b})" for a, b in uniq),
                 [b for _, b in uniq], "Low", ["Keyword match only."])


def ask(con, question):
    ql = question.lower().strip()
    if not ql:
        return reply("Ask me something about Veloxa.", [], "None")
    for h in HANDLERS:
        r = h(con, question, ql)
        if r:
            return r
    return fallback(con, question)
